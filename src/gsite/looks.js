export function loadSiteFonts(theme) {
  const def = SITE_LOOKS[theme];
  if (!def || typeof document === "undefined" || document.getElementById(`gs-font-${theme}`)) return;
  const link = document.createElement("link");
  link.id = `gs-font-${theme}`;
  link.rel = "stylesheet";
  link.href = `https://fonts.googleapis.com/css2?family=${def.fonts}&display=swap`;
  document.head.appendChild(link);
}

