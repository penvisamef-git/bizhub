export function usePortfolioText() {
  const { lang } = useI18n();
  return TEXT[lang] || TEXT.en;
}

export function fmtDay(date, lang) {
  if (!date) return "";
  return new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", year: "numeric" }).format(new Date(date));
}
