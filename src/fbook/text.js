export const startLang = (def) => {
  try {
    const v = localStorage.getItem("fb-lang");
    if (v === "km" || v === "en") return v;
  } catch {
    /* private window */
  }
  return def === "en" ? "en" : "km";
};
export const keepLang = (v) => {
  try {
    localStorage.setItem("fb-lang", v);
  } catch {
    /* private window */
  }
};
