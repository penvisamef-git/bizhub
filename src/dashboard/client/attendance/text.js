// "1:05" style hours from minutes; "25m" under an hour
export const dur = (min) => {
  const m = Math.round(Number(min) || 0);
  if (!m) return "0";
  if (m < 60) return `${m}m`;
  return `${Math.floor(m / 60)}h${m % 60 ? ` ${String(m % 60).padStart(2, "0")}m` : ""}`;
};
// local Cambodia time "08:05" from a date
export const hhmm = (d) => (d ? new Date(new Date(d).getTime() + 7 * 3600000).toISOString().slice(11, 16) : "");
export const todayKH = () => new Date(Date.now() + 7 * 3600000).toISOString().slice(0, 10);
export const fmtDate = (d, lang) => (d ? new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", year: "numeric" }).format(new Date(d)) : "");
export const fmtDay = (day, lang) => {
  const [y, m, dd] = day.split("-").map(Number);
  return new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { weekday: "short", day: "numeric", month: "short", timeZone: "UTC" }).format(new Date(Date.UTC(y, m - 1, dd)));
};
