export const fmtTime = (d, lang) => (d ? new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" }).format(new Date(d)) : "");
export const SITE = PUBLIC_SITE_URL;
export const codeUrl = (slug) => `${PUBLIC_SITE_URL}/x/${slug}`;
