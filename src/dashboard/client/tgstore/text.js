export const fmtDate = (d, lang) => (d ? new Date(d).toLocaleDateString(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", year: "numeric" }) : "");
export const fmtTime = (d) => (d ? new Date(d).toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit" }) : "");
export const ago = (d, x) => {
  if (!d) return "";
  const min = Math.round((Date.now() - new Date(d).getTime()) / 60000);
  if (min < 1) return x.justNow;
  if (min < 60) return x.minAgo.replace("{n}", min);
  const h = Math.round(min / 60);
  if (h < 24) return x.hAgo.replace("{n}", h);
  return x.dAgo.replace("{n}", Math.round(h / 24));
};
export const fill = (s, v) => String(s).replace(/\{(\w+)\}/g, (_, k) => v[k] ?? "");

