export const fmt = (n) => new Intl.NumberFormat("en-US").format(Number(n) || 0);
export const SITE = (typeof window !== "undefined" ? window.location.origin : "").replace(/\/+$/, "");
// $12.50 · 20,000៛
export const money = (cur, v) => {
  const n = Number(v) || 0;
  if (cur === "KHR") return `${new Intl.NumberFormat("en-US").format(Math.round(n))}៛`;
  return `${n < 0 ? "-" : ""}$${new Intl.NumberFormat("en-US", { minimumFractionDigits: Math.abs(n) % 1 ? 2 : 0, maximumFractionDigits: 2 }).format(Math.abs(n))}`;
};
// what someone owes, both currencies: "$12.50 + 20,000៛" (or "$0")
export const owed = (b = {}) => [b.usd > 0 && money("USD", b.usd), b.khr > 0 && money("KHR", b.khr)].filter(Boolean).join(" + ") || money("USD", 0);
export const owes = (b = {}) => (b.usd || 0) > 0 || (b.khr || 0) > 0;
export const totalUsd = (b = {}, rate = 4100) => Math.max(0, b.usd || 0) + Math.max(0, b.khr || 0) / (rate || 4100);
export const fmtDate = (d, lang) => (d ? new Date(d).toLocaleDateString(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", year: "numeric" }) : "");
export const fmtTime = (d, lang) => (d ? new Date(d).toLocaleString(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" }) : "");
// Cambodia day "2026-10-13" for a date input
export const dayOf = (d) => (d ? new Date(new Date(d).getTime() + 7 * 3600000).toISOString().slice(0, 10) : "");
export const fromDay = (day) => (day ? new Date(`${day}T12:00:00+07:00`).toISOString() : null);
// late / due soon / later
export function dueState(c) {
  if (!c?.due_at || !owes(c.balance)) return "";
  const today = dayOf(new Date());
  const due = dayOf(c.due_at);
  if (due < today) return "late";
  const days = Math.round((Date.parse(due) - Date.parse(today)) / 86400000);
  return days === 0 ? "today" : days <= 7 ? "soon" : "later";
}
export const daysLate = (c) => Math.max(0, Math.round((Date.parse(dayOf(new Date())) - Date.parse(dayOf(c.due_at))) / 86400000));

