// payment method names: built-in (texts), the shop's own (mart_payments, set when the data loads) or the name kept on the sale
let customMethods = [];
export const setCustomMethods = (list) => {
  customMethods = Array.isArray(list) ? list : [];
};
export const customMethodOf = (k) => customMethods.find((x) => x.key === k) || null;
export const methodName = (m, k, saved) => m.methods?.[k] || saved || customMethodOf(k)?.name || k;
export const todayKH = () => new Date(Date.now() + 7 * 3600000).toISOString().slice(0, 10);
export const money = (v, cur = "USD") => {
  const n = Number(v) || 0;
  if (n < 0 && Math.abs(n) >= (cur === "KHR" ? 0.5 : 0.005)) return `−${money(-n, cur)}`; // −$0.02, not $-0.02
  return cur === "KHR" ? `${Math.round(Math.abs(n)).toLocaleString("en-US")}៛` : `$${Math.abs(n).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
};
export const riel = (v) => `${Math.round(Number(v) || 0).toLocaleString("en-US")}៛`;
export const fmtDate = (d, lang) => (d ? new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", year: "numeric" }).format(new Date(d)) : "");
export const fmtTime = (d, lang) => (d ? new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { hour: "2-digit", minute: "2-digit", timeZone: "Asia/Phnom_Penh" }).format(new Date(d)) : "");
export const fmtDayTime = (d, lang) => (d ? new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit", timeZone: "Asia/Phnom_Penh" }).format(new Date(d)) : "");
export const fmtDay = (day, lang) => (day ? new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", timeZone: "UTC" }).format(new Date(`${day}T00:00:00Z`)) : "");
export const unitName = (u, lang) => (!u ? "" : lang === "km" ? u.name_km || u.name_en : u.name_en || u.name_km);
export const stockOn = (ctx) => (ctx.pos ? !!ctx.data.stock : !!ctx.data.addons?.mart_stock?.active);
// printing: on (mart_printer), template, paper width, print after each sale
export const printOf = (ctx) =>
  ctx.pos
