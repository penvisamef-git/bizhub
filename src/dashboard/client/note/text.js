// 1.2 MB / 340 KB / 1 GB
export function bytes(n) {
  const v = Number(n) || 0;
  if (v >= 1073741824) return `${(v / 1073741824).toFixed(v >= 10737418240 ? 0 : 1).replace(/\.0$/, "")} GB`;
  if (v >= 1048576) return `${(v / 1048576).toFixed(1).replace(/\.0$/, "")} MB`;
  if (v >= 1024) return `${Math.round(v / 1024)} KB`;
  return `${v} B`;
}
export const fmtDate = (d, lang) => (d ? new Date(d).toLocaleDateString(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", year: "numeric" }) : "");
export const fmtTime = (d, lang) => (d ? new Date(d).toLocaleString(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" }) : "");
// "2 min ago" style (falls back to the date after a week)
export function ago(d, m, lang) {
  if (!d) return "";
  const s = Math.max(0, (Date.now() - new Date(d).getTime()) / 1000);
  if (s < 60) return m.justNow;
  if (s < 3600) return m.minAgo.replace("{n}", Math.floor(s / 60));
  if (s < 86400) return m.hourAgo.replace("{n}", Math.floor(s / 3600));
  if (s < 604800) return m.dayAgo.replace("{n}", Math.floor(s / 86400));
  return fmtDate(d, lang);
}
