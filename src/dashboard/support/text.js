export const fmtWhen = (d, lang) => new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit", timeZone: "Asia/Phnom_Penh" }).format(new Date(d));
export const fmtTime = (d, lang) => new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { hour: "2-digit", minute: "2-digit", timeZone: "Asia/Phnom_Penh" }).format(new Date(d));
export const fmtDayOnly = (d, lang) => new Intl.DateTimeFormat(lang === "km" ? "km-KH" : "en-GB", { weekday: "short", day: "numeric", month: "short", timeZone: "Asia/Phnom_Penh" }).format(new Date(d));
