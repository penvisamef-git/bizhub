// Google fonts for a look (Khmer fallbacks always loaded with the page)
const LOADED = new Set(["Kantumruy Pro"]);
export function loadThemeFonts(keys) {
  if (typeof document === "undefined") return;
  for (const f of keys) {
    if (!f || LOADED.has(f)) continue;
    LOADED.add(f);
    const link = document.createElement("link");
    link.rel = "stylesheet";
    const single = ["Pacifico", "Lobster", "Bebas Neue", "Righteous", "Abril Fatface", "Archivo Black", "Kaushan Script", "Satisfy", "Moul", "Koulen", "DM Serif Display"].includes(f);
    link.href = `https://fonts.googleapis.com/css2?family=${f.replace(/ /g, "+")}${single ? "" : ":wght@400;600;700"}&display=swap`;
    document.head.appendChild(link);
  }
}
const fam = (f) => `'${f}', 'Kantumruy Pro', 'Battambang', system-ui, sans-serif`;
// CSS variables for a look (+ the owner's own colour, if set)
export function themeVars(key, color) {
  const t = MQ_THEMES[key] || MQ_THEMES.classic;
  return { "--q-bg": t.bg, "--q-card": t.card, "--q-ink": t.ink, "--q-muted": t.muted, "--q-accent": color || t.accent, "--q-line": t.line, "--q-r": `${t.r}px`, "--q-hf": fam(t.hf), "--q-bf": fam(t.bf) };
}
