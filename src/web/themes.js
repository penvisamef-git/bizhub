export const WEB_THEME_KEYS = Object.keys(WEB_LOOKS);
export const webLookName = (k, lang) => (lang === "km" ? WEB_LOOKS[k]?.km : WEB_LOOKS[k]?.name) || k;
export const webLookDesc = (k, lang) => (lang === "km" ? WEB_LOOKS[k]?.descKm : WEB_LOOKS[k]?.desc) || "";

export function loadWebFonts(theme) {
  const def = WEB_LOOKS[theme];
  if (!def || typeof document === "undefined" || document.getElementById(`cw-font-${theme}`)) return;
  const link = document.createElement("link");
  link.id = `cw-font-${theme}`;
  link.rel = "stylesheet";
  link.href = `https://fonts.googleapis.com/css2?family=${def.fonts}&display=swap`;
  document.head.appendChild(link);
}

// css variables of a look (+ the owner's colour)
export function webVars(theme, color) {
  const d = WEB_LOOKS[theme] || WEB_LOOKS.classic;
  const accent = color || d.accent;
  return {
    "--cw-bg": d.bg,
    "--cw-fg": d.fg,
    "--cw-card": d.card,
    "--cw-accent": accent,
    "--cw-accent2": d.accent2 || accent,
    "--cw-head": `${d.head}, 'Kantumruy Pro', system-ui, sans-serif`,
    "--cw-body": `${d.body}, 'Kantumruy Pro', system-ui, sans-serif`,
    "--cw-r": `${d.r}px`,
  };
}
