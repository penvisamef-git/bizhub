export function loadThemeFonts(theme) {
  const def = SITE_THEMES[theme];
  if (!def || typeof document === "undefined" || document.getElementById(`st-font-${theme}`)) return;
  const link = document.createElement("link");
  link.id = `st-font-${theme}`;
  link.rel = "stylesheet";
  link.href = `https://fonts.googleapis.com/css2?family=${def.fonts}&display=swap`;
  document.head.appendChild(link);
}
