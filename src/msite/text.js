// the cart lives in the browser (the website and the account page share it): { product_id: qty }
const cartKey = (slug) => `bizhub_mart_cart_${slug}`;
export const cartStore = {
  get: (slug) => {
    try {
      const v = JSON.parse(localStorage.getItem(cartKey(slug)) || "{}");
      return v && typeof v === "object" ? v : {};
    } catch {
      return {};
    }
  },
  set: (slug, cart) => {
    try {
      const clean = Object.fromEntries(Object.entries(cart).filter(([, n]) => n > 0));
      if (Object.keys(clean).length) localStorage.setItem(cartKey(slug), JSON.stringify(clean));
      else localStorage.removeItem(cartKey(slug));
    } catch {
      /* private mode */
    }
  },
};
