export function loadFonts(list) {
  if (typeof document === "undefined") return;
  for (const f of [...new Set(list.filter(Boolean))]) {
    if (f === "Kantumruy Pro") continue; // already on every page
    const id = `ms-font-${f.replace(/ /g, "-")}`;
    if (document.getElementById(id)) continue;
    const link = document.createElement("link");
    link.id = id;
    link.rel = "stylesheet";
    link.href = `https://fonts.googleapis.com/css2?family=${["Righteous", "DM Serif Display"].includes(f) ? f.replace(/ /g, "+") : fontParam(f)}&display=swap`;
    document.head.appendChild(link);
  }
}
