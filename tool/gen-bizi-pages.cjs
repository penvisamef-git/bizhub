// Bizi search (v3.0.0): the list of every business page the ⌘K box can open, made from the dashboards' own
// tab lists (TABS in each *Dashboard.jsx) and their EN / KM tab names (tabs: {...} in each text file), so the
// search always says exactly what the page says. Run after adding or renaming a tab:
//   node tool/gen-bizi-pages.cjs   → src/dashboard/bizi/pages.gen.js
const fs = require("fs");
const path = require("path");
const SRC = path.join(__dirname, "../src/dashboard/client/");
const OUT = path.join(__dirname, "../src/dashboard/bizi/pages.gen.js");

// type → [dashboard file, text files (en, km order inside each)]
const TYPES = {
  tg_store: ["tgstore/TgStoreDashboard.jsx", ["tgstore/text.js"]],
  restaurant: ["restaurant/RestaurantDashboard.jsx", ["restaurant/text.js"]],
  mart: ["mart/MartDashboard.jsx", ["mart/text.js"]],
  guest_house: ["guesthouse/GuestHouseDashboard.jsx", ["guesthouse/text.js", "guesthouse/gh3-text.js"]],
  event: ["event/EventDashboard.jsx", ["event/text.js"]],
  stamp_card: ["stamp/StampDashboard.jsx", ["stamp/text.js"]],
  attendance: ["attendance/AttendanceDashboard.jsx", ["attendance/text.js"]],
  debt_book: ["debt/DebtDashboard.jsx", ["debt/text.js"]],
  menu_qr: ["menuqr/MenuQrDashboard.jsx", ["menuqr/text.js"]],
  flipbook: ["flipbook/FlipBookDashboard.jsx", ["flipbook/text.js"]],
  digital_note: ["note/NoteDashboard.jsx", ["note/text6.js"]],
  website: ["website/WebsiteDashboard.jsx", ["website/text.js"]],
  qr_gen: ["qrgen/QrGenDashboard.jsx", ["qrgen/text.js"]],
};

// the {...} that starts at `from` (skips strings and // comments)
function objAt(src, from) {
  let i = src.indexOf("{", from), depth = 0, q = null;
  const start = i;
  for (; i < src.length; i++) {
    const c = src[i];
    if (q) { if (c === "\\") { i++; continue; } if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === "`") { q = c; continue; }
    if (c === "/" && src[i + 1] === "/") { i = src.indexOf("\n", i); continue; }
    if (c === "{") depth++;
    if (c === "}") { depth--; if (depth === 0) return src.slice(start, i + 1); }
  }
  throw new Error("unbalanced");
}
const strings = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => typeof v === "string"));

const out = {};
let missing = 0;
for (const [type, [dash, texts]] of Object.entries(TYPES)) {
  const d = fs.readFileSync(SRC + dash, "utf8");
  const at = d.indexOf("const TABS = [");
  if (at < 0) throw new Error("no TABS in " + dash);
  const block = d.slice(at, d.indexOf("\n];", at));
  const keys = [...block.matchAll(/\[\s*"([a-z_]+)",\s*[A-Z]/g)].map((m) => m[1]);
  const en = {}, km = {};
  for (const f of texts) {
    const s = fs.readFileSync(SRC + f, "utf8");
    const found = [...s.matchAll(/\btabs:\s*\{/g)].map((m) => strings(new Function(`return (${objAt(s, m.index)});`)()));
    found.forEach((o, i) => Object.assign(i % 2 === 0 ? en : km, o));
  }
  const tabs = keys.filter((k) => en[k]).map((k) => [k, en[k], km[k] || en[k]]);
  const lost = keys.filter((k) => !en[k]);
  if (lost.length) { missing += lost.length; console.log(`  ${type}: no name for ${lost.join(", ")} (left out)`); }
  out[type] = { home: keys[0], tabs };
}
const js = `// GENERATED by tool/gen-bizi-pages.cjs from the dashboards' TABS and text files — do not edit here.
// type → { home: the tab with no ?tab=, tabs: [[key, English, Khmer], …] }
export const BIZI_PAGES = {
${Object.entries(out).map(([k, v]) => `  ${k}: { home: ${JSON.stringify(v.home)}, tabs: [\n${v.tabs.map((x) => `    ${JSON.stringify(x)},`).join("\n")}\n  ] },`).join("\n")}
};
`;
fs.writeFileSync(OUT, js);
console.log(`${Object.keys(out).length} business types, ${Object.values(out).reduce((a, x) => a + x.tabs.length, 0)} pages → ${path.relative(process.cwd(), OUT)}${missing ? ` (${missing} without a name)` : ""}`);
